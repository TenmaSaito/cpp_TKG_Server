template<class T> void SafeUniqueUninit(std::unique_ptr<T> &ptr)
{ // ユニークポインタのバッファ解放処理
	if (ptr != nullptr)
	{ // nullptrでなければ解放
		ptr->Uninit();
		ptr.reset();
	}
}
