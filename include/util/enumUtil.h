#ifndef _ENUM_UTIL_H_		// インクルードガード
#define _ENUM_UTIL_H_

//**********************************************************************************
// *** インクルードファイル ***
//**********************************************************************************
#include <cstddef>
#include <type_traits>

//**********************************************************************************
// *** 列挙型の補助関数名前空間 ***
//**********************************************************************************
namespace EnumUtil
{
	//******************************************************************************
	// *** 列挙型であることを要求するコンセプト ***
	//******************************************************************************
	template<class E>
	concept Enum = std::is_enum_v<E>;

	//******************************************************************************
	// *** 基底型の値へ変換 ***
	//******************************************************************************
	template<Enum E>
	constexpr std::underlying_type_t<E> ToUnderlying(const E value) noexcept
	{
		return static_cast<std::underlying_type_t<E>>(value);
	}

	//******************************************************************************
	// *** 配列の添え字へ変換 ***
	//******************************************************************************
	template<Enum E>
	constexpr size_t ToIndex(const E value) noexcept
	{
		return static_cast<size_t>(ToUnderlying(value));
	}

	//******************************************************************************
	// *** 基底型の値から列挙型へ変換 ***
	//******************************************************************************
	template<Enum E, class T>
	constexpr E FromUnderlying(const T value) noexcept
	{
		return static_cast<E>(value);
	}

	//******************************************************************************
	// *** 範囲判定 [first, end) ***
	//******************************************************************************
	template<Enum E>
	constexpr bool InRange(const E value, const E first, const E end) noexcept
	{
		return ToUnderlying(first) <= ToUnderlying(value) && ToUnderlying(value) < ToUnderlying(end);
	}

	//******************************************************************************
	// *** 範囲判定 [first, last] ***
	//******************************************************************************
	template<Enum E>
	constexpr bool InRangeInclusive(const E value, const E first, const E last) noexcept
	{
		return ToUnderlying(first) <= ToUnderlying(value) && ToUnderlying(value) <= ToUnderlying(last);
	}
}

#endif
