//==================================================================================
// --- メイン関数 ---
//==================================================================================
int main(void)
{
	// WinSockの初期化処理
	WSADATA wsaData = {};
	printf("Winsockの初期化を開始...\n");
	int nError = WSAStartup(WINSOCK_VERSION, &wsaData);
	if (nError != 0)
	{ // エラー出力の場合
		// 入力待機後、プログラムを終了
		printf("WinSockの初期化に失敗！プログラムを終了します！\n");
		rewind(stdin);
		(void)getchar();

		return 0;
	}

	// サーバー関連処理
	ServerFunction();

	// WinSockの終了処理
	WSACleanup();

	// 入力待機
	printf("*** Enterを押して終了! ***\n");
	rewind(stdin);
	(void)getchar();
	return 0;
}

//==================================================================================
// --- サーバーのメイン処理 ---
//==================================================================================
void ServerFunction(void)
{ // サーバー作成
	printf("サーバー作成中...\n");
	std::unique_ptr pServer = std::make_unique<CRankingServer>();		// サーバー
	if (pServer == nullptr)
	{ // サーバー作成失敗
		printf("サーバー作成に失敗！\n");
		return;
	}

	// サーバー初期化
	printf("サーバー初期化中...\n");
	if (FAILED(pServer->Init("data/bin/ranking.bin", 22333, 5)))
	{ // サーバー初期化失敗
		printf("サーバー初期化に失敗！\n");
		return;
	}

	// サーバーの動作開始
	printf("サーバー動作中...\n");
	while (1)
	{ // サーバーを更新
		pServer->Update();
	}

	// サーバーを終了
	printf("サーバー終了中...\n");
	pServer->Uninit();
}